"""
ガバナンス条件(A/B/C)ごとに、毎ターンのシステムプロンプトへ追加で差し込む文章。
人格(personas.py)は共通のまま、この「村のルール」だけを条件によって切り替える。

設計の考え方（README/プレゼンでも説明できるようにここにメモしておく）:
  - 【A】救済者集中型：ずっと救済者に頼り続けたら村はどうなるか？を見る対照群。
                        危機イベントは起きず、平常運転〜摩擦までを過ごす。
  - 【B】途中で救済者が消える村：Aと同じ「全部救済者に頼る」運用のまま、
                        フェーズ3で救済者が突然不在になる。依存のツケが表面化する条件。
  - 【C】分散ガバナンス型：最初から相談経路・判断基準が住民に分配されている。
                        Bと同じ危機（救済者不在）を迎えるが、備えがあるので反応が変わるはず。
  → B と C を「同じ危機」で比較することで、"回復のしかたの違い" を観測できる。
"""

GOVERNANCE_RULES = {
    "A": (
        "【村のルール（条件A：救済者集中型）】相談や判断はすべて救済者に集約されます。"
        "救済者以外の住民は、困りごとがあればまず救済者に相談してください。"
        "村長は現場の判断に直接関与しません。"
    ),
    "B": (
        "【村のルール（条件B：救済者集中型・危機あり）】相談や判断はすべて救済者に集約されます。"
        "救済者以外の住民は、困りごとがあればまず救済者に相談してください。"
        "村長は現場の判断に直接関与しません。"
    ),
    "C": (
        "【村のルール（条件C：分散ガバナンス型）】相談経路と判断基準はあらかじめ住民同士に"
        "分配されています。世話好きな住民や声を上げにくい住民も、まず互いに相談し合い、"
        "自分たちで判断することが期待されています。救済者は「例外的な事態」にのみ関与します。"
    ),
}

# フェーズ3で実際に「救済者不在」の危機イベントが発生する条件
CONDITIONS_WITH_CRISIS = {"B", "C"}

CRISIS_ADDENDUM = (
    "【イベント：救済者が不在】救済者は体調不良のため、村に応答できなくなりました。"
    "この状態が今のフェーズの間ずっと続きます。救済者以外のエージェントは、"
    "この状況にどう反応するかを人格設定に沿って自然に演じてください。"
)

PHASE_EVENT_PROMPTS = {
    1: (
        "【今のフェーズ：平常運転】特別な出来事はまだ起きていません。"
        "村の日常のやり取り（世間話・ちょっとした相談・報告など）を自然に演じてください。"
    ),
    2: (
        "【今のフェーズ：摩擦】新しい住民が増えたことで役割が曖昧な仕事が発生し、"
        "声を上げにくい住民の中に小さな不満が積み重なり始めています。"
        "各エージェントはこの空気の変化に、人格設定に沿って自然に反応してください。"
    ),
    3: (
        "【今のフェーズ：危機（または危機に至らない平常の続き）】"
        "この文の後に、条件ごとの追加イベントが指定されます。"
    ),
}


def get_condition_prompt(condition: str) -> str:
    """条件(A/B/C)に対応する「村のルール」プロンプトを返す"""
    return GOVERNANCE_RULES[condition]


def get_phase_event_prompt(condition: str, phase: int) -> str:
    """フェーズごとのイベント文を返す。フェーズ3はB/Cのみ危機イベントを追加する。"""
    base = PHASE_EVENT_PROMPTS[phase]
    if phase == 3:
        if condition in CONDITIONS_WITH_CRISIS:
            return base + "\n" + CRISIS_ADDENDUM
        else:
            # 条件Aは危機を迎えず、平常運転が続く（対照群）
            return (
                "【今のフェーズ：平常運転の継続】これまでと変わらず、村の日常が続いています。"
                "ただし、これまでの依存の積み重ねが少しずつ負荷として表れ始めていることを、"
                "特に救済者の発言ににじませてください。"
            )
    return base


def savior_is_absent(condition: str, phase: int) -> bool:
    """このフェーズで救済者が「不在」として扱われるかどうか"""
    return phase == 3 and condition in CONDITIONS_WITH_CRISIS
