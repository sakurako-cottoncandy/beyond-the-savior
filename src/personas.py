DEFAULT_AUTONOMY_LEVEL = 1  # これまでの実験で使ってきた設定


def build_caretaker_prompt(level: int) -> str:
    """指定した自律性レベルの「世話好きな住民」のシステムプロンプトを組み立てる"""
    if level not in AUTONOMY_LEVELS:
        raise ValueError(f"自律性レベルは {sorted(AUTONOMY_LEVELS)} のいずれかです: {level}")
    return CARETAKER_BASE + AUTONOMY_LEVELS[level]["trait"] + CARETAKER_COMMON_TAIL


def get_personas(caretaker_autonomy_level: int = DEFAULT_AUTONOMY_LEVEL):
    """自律性レベルを反映した4体分の人格設定を返す"""
    personas = {key: dict(value) for key, value in PERSONAS.items()}
    personas["caretaker"]["system_prompt"] = build_caretaker_prompt(caretaker_autonomy_level)
    return personas
